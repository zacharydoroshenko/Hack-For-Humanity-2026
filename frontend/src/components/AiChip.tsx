import { useId, useState } from "react";
import { IconChevron, IconSpark } from "./Icons";

interface Props {
  label?: string;
  /** Source text the AI read; shown when the chip is opened. */
  source?: string | null;
  sourceLabel?: string;
}

/** "AI-interpreted" label. Click (or Enter) to reveal what the AI read. */
export default function AiChip({ label = "AI-interpreted", source, sourceLabel = "What Gemini read" }: Props) {
  const [open, setOpen] = useState(false);
  const id = useId();
  if (!source) {
    return (
      <span className="ai-chip" title="Generated by Gemini">
        <IconSpark size={14} /> {label}
      </span>
    );
  }
  return (
    <span className="ai-chip-wrap">
      <button
        type="button"
        className="ai-chip"
        aria-expanded={open}
        aria-controls={id}
        onClick={(e) => {
          e.stopPropagation();
          setOpen((o) => !o);
        }}
      >
        <IconSpark size={14} /> {label}
        <IconChevron size={14} style={{ transform: open ? "rotate(180deg)" : undefined }} />
      </button>
      {open && (
        <span id={id} className="ai-source" role="note">
          <strong>{sourceLabel}:</strong> “{source}”
        </span>
      )}
    </span>
  );
}
